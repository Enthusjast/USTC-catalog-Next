import { readFile, mkdir, writeFile, rename, rm } from "node:fs/promises";
import { createHash } from "node:crypto";
import { homedir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildIcourseIndex } from "../src/domain/icourse.ts";

const args = process.argv.slice(2),
  sourceFlag = args.indexOf("--source");
if (
  args.some(
    (arg, index) =>
      !["--source", "--check"].includes(arg) &&
      !(sourceFlag >= 0 && index === sourceFlag + 1),
  ) ||
  (sourceFlag >= 0 &&
    (!args[sourceFlag + 1] || args[sourceFlag + 1].startsWith("--")))
) {
  console.error(
    "用法：node scripts/sync-icourse.mjs [--source 快照.json] [--check]",
  );
  process.exit(2);
}
const source =
    sourceFlag >= 0
      ? resolve(args[sourceFlag + 1])
      : resolve(
          homedir(),
          "reference/class-arrange/icourse_spider/course_rating.json",
        ),
  output = fileURLToPath(
    new URL("../src/data/icourseLinks.ts", import.meta.url),
  );
let temporary;
try {
  const bytes = await readFile(source),
    { index, ...counts } = buildIcourseIndex(
      JSON.parse(bytes.toString("utf8")),
    ),
    sha256 = createHash("sha256").update(bytes).digest("hex"),
    importedAt = new Date().toLocaleDateString("sv-SE", {
      timeZone: "Asia/Shanghai",
    }),
    metadata = {
      community: "https://www.icourse.club/",
      referenceRepository: "https://github.com/RaymondzyLei/class-arrange",
      reference: "class-arrange/icourse_spider/course_rating.json",
      importedAt,
      sha256,
      ...counts,
    },
    content = `// Generated by scripts/sync-icourse.mjs. Snapshot facts; see THIRD_PARTY_NOTICES.md.\n// prettier-ignore\nexport const icourseSource = ${JSON.stringify(metadata, null, 2)};\n// prettier-ignore\nexport const icourseIndex: Readonly<Record<string, string>> = ${JSON.stringify(index, null, 2)};\n`;
  const existing = await readFile(output, "utf8").catch(() => ""),
    existingSource = existing.match(
      /export const icourseSource = ([\s\S]*?);\n/,
    ),
    existingIndex = existing.match(
      /export const icourseIndex:[^=]+ = ([\s\S]*);\n$/,
    );
  const unchanged =
    !!existingSource &&
    !!existingIndex &&
    JSON.parse(existingSource[1]).sha256 === sha256 &&
    JSON.parse(existingSource[1]).referenceRepository ===
      metadata.referenceRepository &&
    existing.includes("// prettier-ignore") &&
    JSON.stringify(JSON.parse(existingIndex[1])) === JSON.stringify(index);
  if (args.includes("--check")) {
    if (!unchanged)
      throw new Error("评课索引与指定快照不同，请执行同步后检查差异。");
    console.log(
      `评课索引一致：${counts.unique} 个唯一匹配，${counts.ambiguous} 个歧义组合。`,
    );
  } else if (unchanged) console.log("评课索引未变化，保留原导入日期。");
  else {
    await mkdir(dirname(output), { recursive: true });
    temporary = `${output}.tmp-${process.pid}`;
    await writeFile(temporary, content, "utf8");
    await rename(temporary, output);
    console.log(
      `已生成 ${counts.unique} 个唯一匹配；${counts.ambiguous} 个歧义组合及 ${counts.unmatchable} 条无教师记录使用搜索。`,
    );
  }
} catch (error) {
  console.error(`${error.message}\n现有评课索引保持不变。`);
  process.exitCode = 2;
} finally {
  if (temporary) await rm(temporary, { force: true });
}
